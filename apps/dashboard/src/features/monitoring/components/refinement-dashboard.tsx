"use client";

import {
  Activity,
  ArrowUpRight,
  CircleAlert,
  Eye,
  Layers,
  ShieldCheck,
  Target,
  Workflow,
} from "lucide-react";
import { useEffect, useState } from "react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardAction, CardContent, CardDescription, CardHeader } from "@/components/ui/card";
import { Label } from "@/components/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { dateTime, label, passedCount, relative, scenarioName } from "@/features/monitoring/format";
import { useMonitoring } from "@/features/monitoring/monitoring-provider";
import { ChangeDiff } from "./change-diff";
import { ConversationFeed } from "./conversation-feed";
import { IterationHistory } from "./iteration-history";
import { ScenarioResults } from "./scenario-results";
import { ScorePanel } from "./score-panel";

type View = "overview" | "conversations" | "evaluations" | "changes" | "iterations";
const headings: Record<View, { title: string; description: string }> = {
  overview: {
    title: "Autonomous refinement",
    description: "Watch your airline assistant learn from every conversation.",
  },
  conversations: {
    title: "Every conversation, as it happens",
    description: "Follow simulated customers and the airline assistant, turn by turn.",
  },
  evaluations: {
    title: "Quality, measured every iteration",
    description: "Four independent criteria. Every scenario must meet the target.",
  },
  changes: {
    title: "A clear view of every improvement",
    description: "Inspect the prompt and code changes generated by the loop.",
  },
  iterations: {
    title: "The path to a better agent",
    description: "Explore each iteration and the evidence behind its results.",
  },
};
export function RefinementDashboard({ view = "overview" }: { view?: View }) {
  const { run, runs, selectedRun, selectRun, connection, receivedAt } = useMonitoring();
  const [iterationKey, setIterationKey] = useState("");
  const [scenarioId, setScenarioId] = useState("");
  const [now, setNow] = useState(Date.now());
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), 10_000);
    return () => clearInterval(timer);
  }, []);
  const selectedNumber = iterationKey.startsWith(`${run?.run_id}:`)
    ? Number(iterationKey.split(":")[1])
    : null;
  const iteration =
    run?.iterations.find((item) => item.number === selectedNumber) || run?.iterations.at(-1);
  const scenario =
    iteration?.scenarios.find((item) => item.id === scenarioId) ||
    iteration?.scenarios.find((item) => item.id === run?.active_scenario) ||
    iteration?.scenarios.findLast((item) => item.status !== "pending") ||
    iteration?.scenarios[0];
  const threshold = run?.pass_score || 8;
  const live = run?.status === "running" && iteration?.number === run.iteration;
  const stale = run?.status === "running" && now - new Date(run.heartbeat_at).getTime() > 30_000;
  const selectIteration = (number: number) => {
    setIterationKey(`${run?.run_id}:${number}`);
    setScenarioId("");
  };
  const feed = (
    <ConversationFeed scenario={scenario} live={!!live && scenario?.status === "simulating"} />
  );
  const scores = (
    <ScorePanel
      scenario={scenario}
      iterations={run?.iterations || []}
      threshold={threshold}
      limit={run?.max_iterations || 5}
    />
  );
  const changes = <ChangeDiff iteration={iteration} />;
  const history = (
    <IterationHistory run={run} selected={iteration?.number} onSelect={selectIteration} />
  );
  const results = (
    <ScenarioResults
      iteration={iteration}
      threshold={threshold}
      selected={scenario?.id}
      onSelect={setScenarioId}
    />
  );
  return (
    <>
      <div className="mb-7 flex flex-wrap items-start justify-between gap-5">
        <div>
          <div className="mb-3 flex items-center gap-2 text-[10px] font-semibold tracking-[0.16em] text-emerald-700 uppercase">
            <span className="h-px w-5 bg-emerald-500" />
            Agent observatory
          </div>
          <h1 className="text-2xl font-semibold tracking-[-0.035em] text-slate-900 sm:text-3xl">
            {headings[view].title}
          </h1>
          <p className="mt-2 text-sm leading-6 text-slate-500">{headings[view].description}</p>
        </div>
        <Badge variant="outline" className="mt-1 h-8 gap-2 px-3 text-[11px]">
          <Eye className="size-3.5 text-emerald-600" aria-hidden="true" />
          Observation only
        </Badge>
      </div>
      <Card className="mb-6 py-3">
        <CardContent className="flex flex-wrap items-center justify-between gap-3">
          <div className="flex flex-wrap items-center gap-3 text-[11px] text-muted-foreground">
            <Workflow className="size-3.5" aria-hidden="true" />
            <Label htmlFor="observed-run" className="text-xs">
              Run
            </Label>
            <Select
              value={selectedRun || "__latest"}
              items={[
                { value: "__latest", label: "Latest run · automatic" },
                ...runs.map((item) => ({
                  value: item.run_id,
                  label: `${dateTime(item.started_at)} · ${item.run_id.slice(0, 8)}`,
                })),
              ]}
              onValueChange={(value) => {
                selectRun(value === "__latest" ? "" : value || "");
                setIterationKey("");
                setScenarioId("");
              }}
            >
              <SelectTrigger
                id="observed-run"
                aria-label="Observed run"
                size="sm"
                className="max-w-[300px] text-xs"
              >
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="__latest">Latest run · automatic</SelectItem>
                {runs.map((item) => (
                  <SelectItem key={item.run_id} value={item.run_id}>
                    {dateTime(item.started_at)} · {item.run_id.slice(0, 8)}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
            {run && <span className="font-mono text-[10px]">{run.run_id.slice(0, 12)}</span>}
          </div>
          <p className="text-[10px] text-muted-foreground">
            {receivedAt
              ? `Last received ${relative(receivedAt, now)}`
              : "Waiting for monitoring connection"}
          </p>
        </CardContent>
      </Card>
      {connection === "reconnecting" && (
        <Alert role="status" className="mb-5 border-amber-200 bg-amber-50 text-amber-800">
          <CircleAlert aria-hidden="true" />
          <AlertTitle>Reconnecting automatically</AlertTitle>
          <AlertDescription>
            {receivedAt
              ? "Connection interrupted. Showing the last received snapshot."
              : "Monitoring is temporarily unavailable."}
          </AlertDescription>
        </Alert>
      )}
      {stale && connection === "connected" && (
        <Alert role="status" className="mb-5 border-amber-200 bg-amber-50 text-amber-800">
          <CircleAlert aria-hidden="true" />
          <AlertTitle>Worker heartbeat is stale</AlertTitle>
          <AlertDescription>
            The worker has stopped reporting. These are its last recorded observations.
          </AlertDescription>
        </Alert>
      )}
      {run?.error && (
        <Alert variant="destructive" className="mb-5">
          <CircleAlert aria-hidden="true" />
          <AlertTitle>Run stopped</AlertTitle>
          <AlertDescription>{run.error}</AlertDescription>
        </Alert>
      )}
      <div className="mb-7 grid grid-cols-1 gap-3 sm:grid-cols-2 xl:grid-cols-4">
        {[
          {
            title: "Run status",
            value: run
              ? label(run.status === "running" ? run.stage : run.status)
              : "Awaiting first run",
            detail: run
              ? stale
                ? "Worker heartbeat is stale"
                : "Fully autonomous execution"
              : "Runs appear automatically",
            icon: Activity,
          },
          {
            title: "Current iteration",
            value: run ? `${run.iteration} of ${run.max_iterations}` : "Not started",
            detail: "Conversations, evaluation, refinement",
            icon: Layers,
          },
          {
            title: "Scenarios passing",
            value: run
              ? `${passedCount(iteration, threshold)} of ${iteration?.scenarios.length || run.scenario_count}`
              : "Awaiting scores",
            detail: "Every criterion must meet the target",
            icon: ShieldCheck,
          },
          {
            title: "Quality target",
            value: run ? `${threshold} / 10` : "Configured per run",
            detail: "Required for all four criteria",
            icon: Target,
          },
        ].map(({ title, value, detail, icon: Icon }) => (
          <Card key={title} size="sm">
            <CardHeader>
              <CardDescription className="text-[11px]">{title}</CardDescription>
              <CardAction>
                <Icon className="size-4 text-muted-foreground" aria-hidden="true" />
              </CardAction>
            </CardHeader>
            <CardContent>
              <p
                className={`text-lg font-semibold tracking-tight ${title === "Run status" && run?.status === "passed" ? "text-primary" : "text-foreground"}`}
              >
                {value}
              </p>
              <p className="mt-2 text-[10px] leading-5 text-muted-foreground">{detail}</p>
            </CardContent>
          </Card>
        ))}
      </div>
      {!run && connection === "connected" && (
        <Alert role="status" className="mb-6 border-primary/20 bg-accent/60">
          <Eye aria-hidden="true" />
          <AlertTitle>Ready to observe</AlertTitle>
          <AlertDescription>
            No refinement runs have been recorded yet. This workspace will update automatically when
            the worker begins.
          </AlertDescription>
        </Alert>
      )}
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2.5">
          <h2 className="text-sm font-semibold tracking-tight text-slate-700">
            {iteration ? `Iteration ${iteration.number}` : "Live workspace"}
          </h2>
          {live && !stale && connection === "connected" && (
            <Badge variant="default">
              <span className="size-1 rounded-full bg-emerald-500 motion-safe:animate-pulse" />
              In progress
            </Badge>
          )}
          {selectedNumber !== null && (
            <Button variant="link" size="xs" onClick={() => setIterationKey("")}>
              Follow latest
              <ArrowUpRight className="size-3" aria-hidden="true" />
            </Button>
          )}
        </div>
        <div className="flex items-center gap-2 text-xs text-muted-foreground">
          <Label htmlFor="observed-scenario" className="text-xs">
            Scenario
          </Label>
          <Select
            value={scenarioId || "__active"}
            items={[
              {
                value: "__active",
                label: scenario
                  ? `Following · ${scenarioName(scenario.id)}`
                  : "Follow active scenario",
              },
              ...(iteration?.scenarios || []).map((item) => ({
                value: item.id,
                label: scenarioName(item.id),
              })),
            ]}
            onValueChange={(value) => setScenarioId(value === "__active" ? "" : value || "")}
          >
            <SelectTrigger
              id="observed-scenario"
              aria-label="Observed scenario"
              size="sm"
              className="max-w-64 text-xs"
            >
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              <SelectItem value="__active">
                {scenario ? `Following · ${scenarioName(scenario.id)}` : "Follow active scenario"}
              </SelectItem>
              {iteration?.scenarios.map((item) => (
                <SelectItem key={item.id} value={item.id}>
                  {scenarioName(item.id)}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
      </div>
      {scenario && (
        <p className="mb-4 max-w-3xl text-[11px] leading-6 text-slate-400">{scenario.goal}</p>
      )}
      <div className="grid items-start gap-5 xl:grid-cols-[minmax(0,1.45fr)_minmax(320px,1fr)]">
        {view === "overview" && (
          <>
            {feed}
            {scores}
            {changes}
            {history}
            <div className="min-w-0 xl:col-span-2">{results}</div>
          </>
        )}
        {view === "conversations" && (
          <>
            {feed}
            {scores}
            <div className="min-w-0 xl:col-span-2">{results}</div>
          </>
        )}
        {view === "evaluations" && (
          <>
            <div className="min-w-0">{results}</div>
            {scores}
          </>
        )}
        {view === "changes" && (
          <>
            {changes}
            {history}
          </>
        )}
        {view === "iterations" && (
          <>
            <div className="min-w-0 space-y-5">
              {results}
              {changes}
            </div>
            {history}
          </>
        )}
      </div>
      <footer className="mt-7 flex flex-wrap items-center justify-between gap-2 border-t border-slate-200/70 pt-4 text-[10px] text-slate-400">
        <span className="flex items-center gap-1.5">
          <ShieldCheck className="size-3" aria-hidden="true" />
          Simulate. Evaluate. Refine. Repeat.
        </span>
        <span>Observation only. The loop makes every decision.</span>
      </footer>
    </>
  );
}
